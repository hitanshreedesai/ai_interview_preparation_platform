import React, { useState, useEffect } from 'react';
import { Link } from 'react-router-dom';
import { api } from '../services/api';
import LoadingSpinner from '../components/LoadingSpinner';
import {
  MessageSquare,
  Sparkles,
  Calendar,
  CheckCircle2,
  XCircle,
  Lightbulb,
  Tag,
  AlertCircle,
} from 'lucide-react';

const Feedback = () => {
  const [feedbacks, setFeedbacks] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  useEffect(() => {
    fetchFeedback();
  }, []);

  const fetchFeedback = async () => {
    try {
      setLoading(true);
      const res = await api.feedback.get();
      if (res?.feedbacks) {
        setFeedbacks(res.feedbacks);
      }
    } catch (err) {
      console.error('Failed to load feedback records:', err);
      setError('Could not retrieve interview feedback.');
    } finally {
      setLoading(false);
    }
  };

  if (loading) {
    return <LoadingSpinner message="Retrieving AI interview feedback reports..." size="large" />;
  }

  return (
    <div>
      <div className="dashboard-header">
        <h1 className="dashboard-title">AI Interview Feedback</h1>
        <p className="dashboard-subtitle">
          Detailed diagnostic reports, actionable advice, and strengths/weaknesses evaluations generated by Gemini AI for each of your interview sessions.
        </p>
      </div>

      {error && (
        <div className="alert alert-danger">
          <AlertCircle size={20} />
          <span>{error}</span>
        </div>
      )}

      {feedbacks.length === 0 ? (
        <div className="card empty-state">
          <MessageSquare className="empty-icon" />
          <h3 className="empty-title">No interview feedback available yet.</h3>
          <p className="empty-desc">
            Complete a mock interview session to receive customized evaluation reports from Gemini AI.
          </p>
          <Link to="/interview" className="btn btn-primary" style={{ marginTop: '0.5rem' }}>
            Start an Interview Now
          </Link>
        </div>
      ) : (
        <div style={{ display: 'flex', flexDirection: 'column', gap: '1.5rem' }}>
          {feedbacks.map((fb) => (
            <div key={fb.id} className="card">
              {/* Card Header */}
              <div
                style={{
                  display: 'flex',
                  justifyContent: 'space-between',
                  alignItems: 'center',
                  flexWrap: 'wrap',
                  gap: '0.75rem',
                  borderBottom: '1px solid var(--border-color)',
                  paddingBottom: '1rem',
                  marginBottom: '1.25rem',
                }}
              >
                <div style={{ display: 'flex', alignItems: 'center', gap: '0.75rem' }}>
                  <div
                    style={{
                      width: '40px',
                      height: '40px',
                      borderRadius: 'var(--radius-md)',
                      backgroundColor: '#eff6ff',
                      color: '#2563eb',
                      display: 'flex',
                      alignItems: 'center',
                      justifyContent: 'center',
                    }}
                  >
                    <Sparkles size={20} />
                  </div>
                  <div>
                    <h2 style={{ fontSize: '1.15rem', fontWeight: 700, color: '#0f172a' }}>
                      {fb.interviewType} Interview Evaluation
                    </h2>
                    <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', color: '#64748b', fontSize: '0.8rem', marginTop: '2px' }}>
                      <Calendar size={13} />
                      <span>{new Date(fb.date).toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' })}</span>
                      <span>•</span>
                      <span>{fb.difficulty} Level</span>
                    </div>
                  </div>
                </div>

                <div
                  style={{
                    backgroundColor: fb.score >= 7 ? '#ecfdf5' : fb.score >= 5 ? '#fffbeb' : '#fef2f2',
                    border: `1px solid ${fb.score >= 7 ? '#86efac' : fb.score >= 5 ? '#fde68a' : '#fca5a5'}`,
                    padding: '0.4rem 1rem',
                    borderRadius: 'var(--radius-full)',
                  }}
                >
                  <span style={{ fontSize: '0.825rem', color: '#64748b', marginRight: '6px' }}>Score:</span>
                  <strong style={{ fontSize: '1.05rem', color: fb.score >= 7 ? '#059669' : fb.score >= 5 ? '#d97706' : '#dc2626' }}>
                    {fb.score} / 10
                  </strong>
                </div>
              </div>

              {/* Strengths and Weaknesses Grid */}
              <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(280px, 1fr))', gap: '1.25rem', marginBottom: '1.25rem' }}>
                {/* Strengths */}
                <div style={{ backgroundColor: '#f0fdf4', padding: '1.1rem', borderRadius: 'var(--radius-md)', border: '1px solid #bbf7d0' }}>
                  <div style={{ display: 'flex', alignItems: 'center', gap: '6px', color: '#15803d', fontWeight: 700, fontSize: '0.95rem', marginBottom: '0.65rem' }}>
                    <CheckCircle2 size={17} />
                    <span>Identified Strengths</span>
                  </div>
                  <ul style={{ paddingLeft: '1.2rem', display: 'flex', flexDirection: 'column', gap: '0.35rem', fontSize: '0.875rem', color: '#166534' }}>
                    {fb.strengths?.map((s, idx) => (
                      <li key={idx}>{s}</li>
                    ))}
                  </ul>
                </div>

                {/* Weaknesses */}
                <div style={{ backgroundColor: '#fff7ed', padding: '1.1rem', borderRadius: 'var(--radius-md)', border: '1px solid #fed7aa' }}>
                  <div style={{ display: 'flex', alignItems: 'center', gap: '6px', color: '#c2410c', fontWeight: 700, fontSize: '0.95rem', marginBottom: '0.65rem' }}>
                    <XCircle size={17} />
                    <span>Identified Weaknesses</span>
                  </div>
                  <ul style={{ paddingLeft: '1.2rem', display: 'flex', flexDirection: 'column', gap: '0.35rem', fontSize: '0.875rem', color: '#9a3412' }}>
                    {fb.weaknesses?.map((w, idx) => (
                      <li key={idx}>{w}</li>
                    ))}
                  </ul>
                </div>
              </div>

              {/* Suggestions */}
              {fb.suggestions?.length > 0 && (
                <div style={{ backgroundColor: '#f8fafc', padding: '1rem', borderRadius: 'var(--radius-md)', border: '1px solid var(--border-color)', marginBottom: '1rem' }}>
                  <div style={{ display: 'flex', alignItems: 'center', gap: '6px', color: '#1e40af', fontWeight: 700, fontSize: '0.9rem', marginBottom: '0.5rem' }}>
                    <Lightbulb size={17} />
                    <span>Actionable Recommendations</span>
                  </div>
                  <ul style={{ paddingLeft: '1.2rem', display: 'flex', flexDirection: 'column', gap: '0.35rem', fontSize: '0.875rem', color: '#334155' }}>
                    {fb.suggestions.map((sug, idx) => (
                      <li key={idx}>{sug}</li>
                    ))}
                  </ul>
                </div>
              )}

              {/* Weak Topics Tags */}
              {fb.weakTopics?.length > 0 && (
                <div style={{ display: 'flex', alignItems: 'center', flexWrap: 'wrap', gap: '0.5rem' }}>
                  <span style={{ fontSize: '0.8rem', color: '#64748b', fontWeight: 600, display: 'flex', alignItems: 'center', gap: '4px' }}>
                    <Tag size={13} />
                    Focus Topics:
                  </span>
                  {fb.weakTopics.map((wt, idx) => (
                    <span key={idx} className="badge badge-amber">
                      {wt.topic} ({wt.percentage}%)
                    </span>
                  ))}
                </div>
              )}
            </div>
          ))}
        </div>
      )}
    </div>
  );
};

export default Feedback;
